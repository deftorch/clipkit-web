import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

// 1. Ensure directories exist
const skillDir = path.resolve(ROOT, 'skills/clipkit');
const refsDir = path.resolve(skillDir, 'references');
const scriptsDir = path.resolve(skillDir, 'scripts');
const examplesDir = path.resolve(skillDir, 'assets/examples');

for (const d of [refsDir, scriptsDir, examplesDir]) {
  if (!fs.existsSync(d)) {
    fs.mkdirSync(d, { recursive: true });
  }
}

// 2. Generate references/channels.md from motus.json and parts.json
const motus = JSON.parse(
  fs.readFileSync(path.resolve(ROOT, 'src/data/rigs/motus.json'), 'utf8'),
);
const parts = JSON.parse(
  fs.readFileSync(path.resolve(ROOT, 'src/data/parts.json'), 'utf8'),
);

let doc = `# ClipKit Humanoid Rig Channels & Limits Reference\n\n`;
doc += `> Auto-generated by \`npm run build:skill\`. Do not edit manually.\n\n`;
doc += `This reference documents all valid rotation and displacement channels for the Motus humanoid rig, grouped by anatomical body part.\n\n`;

for (const [partName, partDef] of Object.entries(parts)) {
  doc += `## Part: \`${partName.toUpperCase()}\`\n\n`;
  if (partDef.joints) {
    doc += `**Anatomical Joints:** ${partDef.joints.join(', ')}\n\n`;
  }

  doc += `| Channel | Bone | Type | Min | Max | Default | Description |\n`;
  doc += `|---|---|---|---|---|---|---|\n`;

  for (const chName of partDef.channels || []) {
    const ch = motus.channels[chName];
    if (ch) {
      const boneStr = ch.bone || (ch.bones ? Object.keys(ch.bones).join(', ') : '');
      const unit = ch.unit === 'm' ? 'm' : '°';
      const minStr = ch.range ? `${ch.range[0]}${unit}` : (ch.min != null ? `${ch.min}${unit}` : 'unbounded');
      const maxStr = ch.range ? `${ch.range[1]}${unit}` : (ch.max != null ? `${ch.max}${unit}` : 'unbounded');
      const defStr = `${ch.default ?? 0}${unit}`;
      doc += `| \`${chName}\` | \`${boneStr}\` | \`${ch.type || 'rot'}\` | ${minStr} | ${maxStr} | ${defStr} | ${ch.desc || ''} |\n`;
    }
  }

  if (partDef.aims) {
    for (const a of partDef.aims) {
      const aim = motus.aims?.[a];
      const elevRange = aim?.range?.elev || [-95, 175];
      const azimRange = aim?.range?.azim || [-100, 140];
      const rollRange = aim?.range?.roll || [-120, 120];
      const elevDef = aim?.default?.elev ?? -75;
      const azimDef = aim?.default?.azim ?? 0;
      const rollDef = aim?.default?.roll ?? 0;
      doc += `| \`${a}_elev\` | \`${a}\` | \`aim\` | ${elevRange[0]}° | ${elevRange[1]}° | ${elevDef}° | Aim elevation angle (horizontal = 0°) |\n`;
      doc += `| \`${a}_azim\` | \`${a}\` | \`aim\` | ${azimRange[0]}° | ${azimRange[1]}° | ${azimDef}° | Aim azimuth angle (forward = 90°) |\n`;
      doc += `| \`${a}_roll\` | \`${a}\` | \`aim\` | ${rollRange[0]}° | ${rollRange[1]}° | ${rollDef}° | Aim axial roll angle |\n`;
    }
  }

  if (partDef.expressions) {
    doc += `\n*Supports all standard VRM 1.0 blend shape expressions (see [face.md](face.md)).*\n`;
  }
  if (partDef.move) {
    doc += `\n*Supports 3D linear root translation via \`move: [x, y, z]\`.*\n`;
  }

  doc += `\n---\n\n`;
}

const channelsMdPath = path.resolve(refsDir, 'channels.md');
fs.writeFileSync(channelsMdPath, doc, 'utf8');
console.log(`Generated: ${channelsMdPath}`);

// 3. Generate references/rules.md from limits.json and rule registry
const limits = JSON.parse(
  fs.readFileSync(path.resolve(ROOT, 'src/data/limits.json'), 'utf8'),
);

let rulesDoc = `# ClipKit Validation Rules & Thresholds Reference\n\n`;
rulesDoc += `> Auto-generated by \`npm run build:skill\`. Do not edit manually.\n\n`;
rulesDoc += `This reference documents the diagnostic rule codes, severity levels, and mathematical thresholds enforced by ClipKit's validation engine.\n\n`;

rulesDoc += `## Diagnostic Severity Levels\n\n`;
rulesDoc += `- \`FAIL\`: Unacceptable violation of anatomical constraints, physics boundaries, or schema integrity. Disallows publication.\n`;
rulesDoc += `- \`WARN\`: Biological implausibility, potential foot sliding, or high acceleration that may degrade animation quality.\n`;
rulesDoc += `- \`INFO\`: Structural notifications, layer duration adjustments, or performance tips.\n\n`;

rulesDoc += `## Physics & Speed Limits by Animation Style\n\n`;
rulesDoc += `| Style | Angular Speed Warn (°/s) | Angular Speed Fail (°/s) | Angular Accel Warn (°/s²) | Loop Pose Diff Max (°) | Root Speed Warn (m/s) | Root Speed Fail (m/s) |\n`;
rulesDoc += `|---|---|---|---|---|---|---|\n`;
for (const [styleName, cfg] of Object.entries(limits.styles)) {
  rulesDoc += `| \`${styleName}\` | ${cfg.ang_speed_warn} | ${cfg.ang_speed_fail} | ${cfg.ang_accel_warn.toLocaleString()} | ${cfg.loop_pose_diff_deg}° | ${cfg.root_speed_warn} | ${cfg.root_speed_fail} |\n`;
}

rulesDoc += `\n## Biological & Floor Constraints\n\n`;
rulesDoc += `- **Knee Flexion**: \`${limits.anatomy.knee_flex_min}°\` to \`${limits.anatomy.knee_flex_max}°\` (knees only bend backwards).\n`;
rulesDoc += `- **Elbow Flexion**: Max \`${limits.anatomy.elbow_flex_max}°\` (elbows only bend inward).\n`;
rulesDoc += `- **Neck Bending**: Max \`${limits.anatomy.neck_bend_max}°\` total inclination.\n`;
rulesDoc += `- **Floor Penetration**: Max \`${limits.floor.penetration_fail_m}m\` below ground baseline ($Y < 0$).\n`;
rulesDoc += `- **Foot Slide Threshold**: Ground movement exceeding \`${limits.floor.slide_warn_ms} m/s\` during active planted windows emits \`FOOT_SLIDE\`.\n\n`;

rulesDoc += `## Canonical Rule Codes\n\n`;
rulesDoc += `| Code | Default Level | Description |\n`;
rulesDoc += `|---|---|---|\n`;
rulesDoc += `| \`SPEED_LIMIT\` | FAIL / WARN | Joint angular velocity exceeds threshold for active style |\n`;
rulesDoc += `| \`ACCEL_LIMIT\` | WARN | Joint angular acceleration exceeds jerk/inertia threshold |\n`;
rulesDoc += `| \`ANATOMY_KNEE\` | FAIL | Knee hyper-extension or inversion |\n`;
rulesDoc += `| \`ANATOMY_ELBOW\` | FAIL | Elbow flexion exceeding physical joint limits |\n`;
rulesDoc += `| \`ANATOMY_NECK\` | FAIL | Neck angle exceeding safe cervical range |\n`;
rulesDoc += `| \`FLOOR_PENETRATION\` | FAIL | Feet or body joints penetrating below floor baseline |\n`;
rulesDoc += `| \`FOOT_SLIDE\` | WARN | Foot translation detected during declared planted window |\n`;
rulesDoc += `| \`ROOT_MOTION_SPEED\` | FAIL / WARN | Root displacement speed exceeds realistic locomotion bounds |\n`;
rulesDoc += `| \`ROOT_MOTION_CLAIM_DIST\` | WARN | Measured root distance does not match declared claim |\n`;
rulesDoc += `| \`ROOT_MOTION_CLAIM_DUR\` | WARN | Measured airtime or motion duration deviates from claim |\n`;
rulesDoc += `| \`LOOP_MISMATCH\` | FAIL | First and last frames do not match on looping clip |\n`;
rulesDoc += `| \`WINDOW_INVALID\` | FAIL | Window intervals reversed ($t_0 > t_1$) or out of range |\n`;
rulesDoc += `| \`WINDOW_SEQUENCE\` | FAIL | Window interval extends beyond clip duration |\n`;
rulesDoc += `| \`EVENT_OUT_OF_BOUNDS\` | FAIL | Event timestamp occurs outside $[0, \\text{duration}]$ |\n`;
rulesDoc += `| \`CHANNEL_UNKNOWN\` | FAIL | Channel name not found in target rig definition |\n`;
rulesDoc += `| \`CHANNEL_RANGE_EXCEEDED\` | FAIL | Keyframe value exceeds mechanical channel range |\n`;
rulesDoc += `| \`VRM10_REQUIRED_BONES\` | FAIL | Missing mandatory VRM humanoid standard bones |\n`;
rulesDoc += `| \`VRM10_INVALID_BONE\` | FAIL | Unrecognized bone identifier in VRM mapping |\n`;
rulesDoc += `| \`VRM10_NON_HIPS_POS\` | FAIL | Position keyframe applied to non-hips bone |\n`;
rulesDoc += `| \`VRM10_EXPRESSIONS\` | FAIL | Invalid VRM blend shape expression preset name |\n`;
rulesDoc += `| \`VERSION_FORMAT\` | FAIL | Invalid or unsupported format version |\n`;
rulesDoc += `| \`CHANGELOG_INVALID\` | FAIL | Changelog missing or improperly structured |\n`;
rulesDoc += `| \`CHANGELOG_VERSION_MISMATCH\` | FAIL | Latest changelog entry does not match version number |\n`;
rulesDoc += `| \`SCHEMA_ERROR\` | FAIL | JSON structure violates ClipKit DSL schema |\n`;
rulesDoc += `| \`LAYER_NOT_FOUND\` | FAIL | Referenced pose or clip layer file could not be resolved |\n`;
rulesDoc += `| \`LAYER_DURATION_CLIPPED\` | INFO | Layer timing clipped to fit parent duration |\n`;
rulesDoc += `| \`AIM_ADDITIVE_APPROX\` | INFO | Aim IK additive mode evaluated as spherical approximation |\n`;
rulesDoc += `| \`CHANNEL_COLLISION\` | WARN | Multiple layers write to the same channel with same priority |\n`;
rulesDoc += `| \`TORSO_OVERRIDE_CONFLICT\` | WARN | Torso layer conflicts with root vertical displacement |\n`;
rulesDoc += `| \`WINDOW_COLLISION\` | WARN | Overlapping gameplay window definitions across layers |\n`;
rulesDoc += `| \`MOVE_COLLISION\` | WARN | Multiple layers attempting concurrent root motion |\n`;

const rulesMdPath = path.resolve(refsDir, 'rules.md');
fs.writeFileSync(rulesMdPath, rulesDoc, 'utf8');
console.log(`Generated: ${rulesMdPath}`);

// 4. Copy standalone CLI into skills/clipkit/scripts/clipkit.mjs
const cliSrc = path.resolve(ROOT, 'bin/clipkit.mjs');
const cliDest = path.resolve(scriptsDir, 'clipkit.mjs');
if (fs.existsSync(cliSrc)) {
  fs.copyFileSync(cliSrc, cliDest);
  fs.chmodSync(cliDest, 0o755);
  console.log(`Copied bundled CLI to: ${cliDest}`);
} else {
  console.warn(`CLI bundle ${cliSrc} not found. Run npm run build:cli first.`);
}

// 5. Copy examples
const exampleFiles = [
  'slash.json',
  'dodge.json',
  'jump.json',
  'hands_eyes_jaw.json',
];
for (const file of exampleFiles) {
  const src = path.resolve(ROOT, 'src/data/clips', file);
  const dest = path.resolve(examplesDir, file);
  if (fs.existsSync(src)) {
    fs.copyFileSync(src, dest);
  }
}
console.log(
  `Copied ${exampleFiles.length} reference examples to: ${examplesDir}`,
);

// 6. Package skills/clipkit.skill
const skillArchive = path.resolve(ROOT, 'skills/clipkit.skill');
if (fs.existsSync(skillArchive)) {
  fs.unlinkSync(skillArchive);
}
try {
  execSync(
    `cd "${skillDir}" && zip -r -q "${skillArchive}" . -x "evals/scratch_evals/*"`,
  );
  console.log(`Packaged skill archive to: ${skillArchive}`);
} catch (err) {
  console.error(`Failed to create skill zip archive: ${err.message}`);
}

console.log('Skill build complete!');

